/**
 * Refreshes src/data/contributions.json from GitHub.
 *   pnpm contributions:update            # all years with activity
 *   pnpm contributions:update 2025 2026  # only these years (others are kept)
 * Only validated years are written; failures leave the previous data untouched.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fetchYear } from "../src/lib/contributions/github.ts";
import { encodeYear, type StoredSnapshot, type StoredYear } from "../src/lib/contributions/snapshot.ts";

const SNAPSHOT = new URL("../src/data/contributions.json", import.meta.url);
const CV = new URL("../cv.json", import.meta.url);
const FIRST_POSSIBLE_YEAR = 2008;

const cv = JSON.parse(await readFile(CV, "utf8"));
const username: string | undefined = cv.basics.profiles.find((p: { network: string }) => p.network === "GitHub")?.username;
if (!username) throw new Error("No GitHub profile in cv.json");

let previous: StoredSnapshot = { username, years: [] };
try {
	previous = JSON.parse(await readFile(SNAPSHOT, "utf8"));
} catch {
	console.log("No existing snapshot, creating one.");
}

const years = new Map<number, StoredYear>(previous.username === username ? previous.years.map((y) => [y.year, y]) : []);
const requested = process.argv.slice(2).map(Number).filter(Number.isInteger);
const currentYear = new Date().getUTCFullYear();

async function update(year: number): Promise<number | undefined> {
	try {
		const data = await fetchYear(username!, year, { timeoutMs: 15_000 });
		years.set(year, encodeYear(data));
		console.log(`✔ ${year}: ${data.total} contributions`);
		return data.total;
	} catch (error) {
		console.error(`✖ ${year}: ${(error as Error).message} (kept previous data)`);
		return undefined;
	}
}

if (requested.length > 0) {
	for (const year of requested) await update(year);
} else {
	// Walk back from the current year until two consecutive years without activity.
	let emptyStreak = 0;
	for (let year = currentYear; year >= FIRST_POSSIBLE_YEAR && emptyStreak < 2; year--) {
		const total = await update(year);
		if (total === 0) {
			emptyStreak++;
			if (year !== currentYear) years.delete(year);
		} else emptyStreak = 0;
	}
}

const output: StoredSnapshot = {
	$comment: "Generated by scripts/update-contributions.ts — run `pnpm contributions:update`. Do not edit by hand.",
	username,
	years: [...years.values()].sort((a, b) => b.year - a.year),
};
// One line per year's counts keeps diffs reviewable without a 365-line array.
const json = JSON.stringify(output, null, "\t").replace(/"counts": \[[\s\d,]+\]/g, (m) => m.replace(/\s+/g, " ").replace("[ ", "[").replace(" ]", "]"));
await writeFile(SNAPSHOT, json + "\n");
console.log(`Saved ${output.years.length} years to src/data/contributions.json`);
